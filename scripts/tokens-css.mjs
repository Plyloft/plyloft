#!/usr/bin/env node
// UX-2.1 (ADR 0007): the one-scale token block of src/App.css, generated from
// docs/ux-language/tokens.json — a copy of the Ply Design System's approved
// tokens. The block sits between the two markers below; nothing else in
// App.css is touched. src/lib/designTokens.test.ts fails when they drift.
//
//   node scripts/tokens-css.mjs --write   regenerate the block in App.css
//   node scripts/tokens-css.mjs --check   exit 1 when the block is stale
//
// Left out on purpose: the design system's `fontSize` family. It re-values
// the legacy names (--text-md …, --page-* sizes) onto the one scale for the
// design system's own previews; in the app each surface moves to the
// `--type-*` tokens in its own cycle (C3–C9), so the legacy sizes keep their
// values in the hand-written block until then.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const BEGIN = "/* @tokens:begin — generated by scripts/tokens-css.mjs from docs/ux-language/tokens.json; do not edit */";
export const END = "/* @tokens:end */";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_FILE = join(ROOT, "docs/ux-language/tokens.json");
export const CSS_FILE = join(ROOT, "src/App.css");

const alias = (v) => v.replace(/^\{(.+)\}$/, "var(--$1)");

function themed(tokens, theme, first) {
  const out = [];
  for (const t of tokens) {
    const v = typeof t.value === "string" ? (theme === first ? t.value : undefined) : t.value[theme];
    if (v !== undefined) out.push(`  --${t.name}: ${alias(v)};`);
  }
  return out;
}

export function generate(tokens) {
  const themes = tokens.color.themes.map((t) => t.id);
  const [first] = themes;
  const colourish = [...tokens.color.tokens, ...tokens.shadow.tokens];
  const block = (sel, lines) => [`${sel} {`, ...lines, "}"];
  const lines = [BEGIN];
  lines.push(...block(":root", themed(colourish, first, first)));
  for (const theme of themes.slice(1)) {
    const own = themed(colourish, theme, first);
    if (theme === "dark") {
      // Before JS sets data-theme, an OS in dark mode gets the dark values.
      lines.push("@media (prefers-color-scheme: dark) {");
      lines.push(...block(`  :root:not([data-theme="light"])`, own.map((l) => "  " + l)));
      lines.push("}");
    }
    lines.push(...block(`:root[data-theme="${theme}"]`, own));
  }
  const plain = [];
  for (const fam of ["spacing", "radius", "size", "duration", "easing"]) {
    for (const t of tokens[fam].tokens) plain.push(`  --${t.name}: ${t.value};`);
  }
  for (const [k, v] of Object.entries(tokens.type.families)) plain.push(`  --font-${k}: ${v};`);
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      plain.push(`  --type-${s.name}: ${s.fontSize};`);
      plain.push(`  --type-${s.name}-lh: ${s.lineHeight};`);
      plain.push(`  --type-${s.name}-weight: ${s.fontWeight};`);
    }
  }
  lines.push(...block(":root", plain));
  // A preset replaces claude-accent only, with its value for the theme.
  for (const p of ["violet", "cyan", "magenta", "sunset"]) {
    lines.push(`:root[data-accent="${p}"] { --claude-accent: var(--accent-${p}); --on-accent: var(--on-accent-preset); }`);
  }
  lines.push(END);
  return lines.join("\n");
}

export function currentBlock(css) {
  const a = css.indexOf(BEGIN);
  const b = css.indexOf(END);
  if (a < 0 || b < a) return null;
  return css.slice(a, b + END.length);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tokens = JSON.parse(readFileSync(TOKENS_FILE, "utf8"));
  const css = readFileSync(CSS_FILE, "utf8");
  const want = generate(tokens);
  const have = currentBlock(css);
  if (process.argv.includes("--write")) {
    if (have === null) throw new Error("App.css has no @tokens markers");
    writeFileSync(CSS_FILE, css.replace(have, want));
    console.log("tokens-css: App.css block regenerated");
  } else {
    const ok = have === want;
    console.log(ok ? "tokens-css: App.css is in step with tokens.json" : "tokens-css: App.css block is stale — run with --write");
    process.exit(ok ? 0 : 1);
  }
}
